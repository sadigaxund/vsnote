#!/usr/bin/env node
/**
 * Codegen: reads `material-icon-theme`'s upstream manifest
 * (`node_modules/material-icon-theme/dist/material-icons.json`, ~450KB
 * covering ~12,800 filename/extension/folder-name mappings) and emits a
 * small curated TypeScript module — `src/components/local/materialIcons.curated.ts`
 * — covering only the file types, filenames, and folder names this app
 * plausibly encounters.
 *
 * Why: `FileIcon`'s resolver used to import the *entire* upstream manifest
 * (behind a lazy `import()`, but the file tree needs icons at first paint,
 * so "lazy" only delayed it by milliseconds — every cold boot still fetched
 * the whole ~450KB manifest + a ~160KB `import.meta.glob` loader table just
 * to render a dozen icons). This script trims that to what's actually
 * needed; `materialIconLoader.ts` still keeps the *full* manifest + glob
 * table as a lazy fallback for the rare file type outside this curated set,
 * so nothing loses generic VSCode-style resolution — it just isn't paid for
 * on every boot.
 *
 * Run manually after bumping `material-icon-theme` or editing the curated
 * lists below: `node scripts/generate-icon-manifest.mjs`. Output is
 * committed (not generated at build time) so `npm run build` never depends
 * on a codegen step succeeding.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "..");

const manifest = JSON.parse(
  readFileSync(path.join(repoRoot, "node_modules/material-icon-theme/dist/material-icons.json"), "utf8"),
);

// ---- Curated coverage -----------------------------------------------------
// The demo vault's own needs (md/ts/tsx/css/csv/png/json, notes/src/assets,
// architecture.md's exact-filename special case) plus a generic "typical web
// + dev project" set, so most real vaults/repos resolve without ever
// touching the full fallback manifest.
const EXTENSIONS = [
  "md", "markdown", "mdx", "ts", "tsx", "js", "jsx", "mjs", "cjs", "json", "jsonc",
  "css", "scss", "sass", "less", "html", "htm", "csv", "tsv", "png", "jpg", "jpeg",
  "gif", "svg", "webp", "ico", "yml", "yaml", "toml", "xml", "sh", "bash", "zsh",
  "py", "rs", "go", "java", "rb", "php", "sql", "lock", "txt", "pdf", "zip", "env",
  "ini", "conf", "log", "vue", "svelte", "graphql", "gql", "wasm", "docker",
];

const FILE_NAMES = [
  "package.json", "package-lock.json", "tsconfig.json", "readme.md", "license",
  ".gitignore", ".gitattributes", "dockerfile", "docker-compose.yml", "vite.config.ts",
  "webpack.config.js", ".env", ".eslintrc", ".prettierrc", "makefile", ".npmrc",
  "cargo.toml", "go.mod", "requirements.txt",
  // Demo-vault-specific (also the pack's own real special case, kept as
  // proof the resolver's fileNames-before-fileExtensions ordering works).
  "architecture.md",
];

const FOLDER_NAMES = [
  "src", "notes", "assets", "docs", "dist", "build", "node_modules", "public",
  "test", "tests", "__tests__", "components", "images", "img", "styles", "scripts",
  "config", "lib", "utils", "hooks", "api", "server", "client", ".git", ".github",
  ".vscode",
];

function iconPathToFilename(iconPath) {
  return iconPath.replace("./../icons/", "");
}

function pick(sourceMap, keys) {
  const out = {};
  for (const key of keys) {
    const value = sourceMap[key];
    if (value) out[key] = value;
  }
  return out;
}

const curatedFileExtensions = pick(manifest.fileExtensions, EXTENSIONS);
const curatedFileNames = pick(manifest.fileNames, FILE_NAMES);
const curatedFolderNames = pick(manifest.folderNames, FOLDER_NAMES);
const curatedFolderNamesExpanded = pick(manifest.folderNamesExpanded, FOLDER_NAMES);

const usedIconKeys = new Set([
  manifest.file,
  manifest.folder,
  manifest.folderExpanded,
  ...Object.values(curatedFileExtensions),
  ...Object.values(curatedFileNames),
  ...Object.values(curatedFolderNames),
  ...Object.values(curatedFolderNamesExpanded),
]);

const iconKeyToFilename = {};
for (const key of usedIconKeys) {
  const def = manifest.iconDefinitions[key];
  if (!def) throw new Error(`No iconDefinitions entry for curated icon key "${key}"`);
  iconKeyToFilename[key] = iconPathToFilename(def.iconPath);
}

const sortedKeys = [...usedIconKeys].sort();

const banner = `/**
 * GENERATED by scripts/generate-icon-manifest.mjs — do not hand-edit.
 * Regenerate: \`node scripts/generate-icon-manifest.mjs\` (after bumping
 * material-icon-theme or editing the curated lists in that script).
 *
 * A small, curated slice of material-icon-theme's manifest (see that
 * script's header for why) plus one explicit lazy \`import()\` per curated
 * icon SVG — a small, fixed routing table instead of the full package's
 * \`import.meta.glob\` over all ~1250 icons, so a cold boot only pays for
 * the icons this curated set can name, not the whole pack's lookup tables.
 */
import type { FileKind } from "../../types";

export interface CuratedManifest {
  file: string;
  folder: string;
  folderExpanded: string;
  fileExtensions: Record<string, string>;
  fileNames: Record<string, string>;
  folderNames: Record<string, string>;
  folderNamesExpanded: Record<string, string>;
}
`;

const manifestSrc = `export const curatedManifest: CuratedManifest = ${JSON.stringify(
  {
    file: manifest.file,
    folder: manifest.folder,
    folderExpanded: manifest.folderExpanded,
    fileExtensions: curatedFileExtensions,
    fileNames: curatedFileNames,
    folderNames: curatedFolderNames,
    folderNamesExpanded: curatedFolderNamesExpanded,
  },
  null,
  2,
)};
`;

const loaderLines = sortedKeys
  .map((key) => {
    const filename = iconKeyToFilename[key];
    return `  ${JSON.stringify(key)}: () =>\n    import("material-icon-theme/icons/${filename}?url").then((m) => m.default),`;
  })
  .join("\n");

const loaderSrc = `
/** One explicit dynamic import per curated icon — Vite code-splits each into
 * its own tiny chunk, fetched only if/when that specific icon is rendered. */
export const curatedIconLoaders: Record<string, () => Promise<string>> = {
${loaderLines}
};
`;

// Representative extension per our small internal FileKind enum, mirrored
// here (not derived from CuratedManifest — it's a fixed, tiny mapping) so
// kind-only FileIcon callers (no `name` prop) still resolve sensibly.
const kindFallbackSrc = `
export const KIND_FALLBACK_EXT: Partial<Record<FileKind, string>> = {
  md: "md",
  ts: "ts",
  tsx: "tsx",
  json: "json",
  css: "css",
  csv: "csv",
  image: "png",
};
`;

const out = banner + "\n" + manifestSrc + loaderSrc + kindFallbackSrc;
const outPath = path.join(repoRoot, "src/components/local/materialIcons.curated.ts");
writeFileSync(outPath, out);

console.log(`Wrote ${outPath}`);
console.log(
  `Curated coverage: ${Object.keys(curatedFileExtensions).length} extensions, ` +
    `${Object.keys(curatedFileNames).length} filenames, ` +
    `${Object.keys(curatedFolderNames).length} folder names, ` +
    `${sortedKeys.length} distinct icons.`,
);
